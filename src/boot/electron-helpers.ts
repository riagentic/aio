/** Slugifies a title for use as Electron app name (stable userData path) */
export function toSlug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") ||
    "aio-app";
}

/** Safely escapes a URL for embedding in executeJavaScript string.
 *  Handles backslashes and single quotes to prevent injection. */
export function escapeForExecuteJavaScript(url: string): string {
  return url.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

/** Checks Electron version constraints.
 *  Throws if the running Electron version doesn't meet minimum requirements. */
export function requireElectronVersion(minMajor: number, minMinor = 0): void {
  const proc = globalThis as unknown as {
    process?: { versions?: { electron?: string } };
  };
  const v = proc.process?.versions?.electron;
  if (!v) return; // Not running in Electron
  const [major, minor] = v.split(".").map(Number);
  if (major === undefined || isNaN(major)) return;
  if (major < minMajor || (major === minMajor && (minor ?? 0) < minMinor)) {
    throw new Error(
      `Electron ${v} does not meet minimum requirement ${minMajor}.${minMinor}. ` +
        `Upgrade Electron or use a lower API target.`,
    );
  }
}

