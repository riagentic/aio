/** Builds the will-navigate handler code with proper URL validation.
 *  Returns a typed string for use in Electron main script template. */
export function buildWillNavigateHandler(appOrigin: string): string {
  return `
  const _appOrigin = ${JSON.stringify(appOrigin)};
  win.webContents.on('will-navigate', (event, navUrl) => {
    try {
      const u = new URL(navUrl);
      if (u.origin === _appOrigin && (u.pathname === '/' || u.pathname === '')) return;
    } catch {}
    event.preventDefault();
    const escaped = '${/* will be replaced at runtime */ ""}'.replace(/\\\\/g, '\\\\\\\\').replace(/'/g, "\\\\'");
    win.webContents.executeJavaScript(
      "window.dispatchEvent(new CustomEvent('aio:navigate',{detail:{url:'" + escaped + "'}}))"
    ).catch(() => {});
  });`.trim();
}

/** Builds certificate-error handler for self-signed localhost certs.
 *  Only accepts localhost/127.0.0.1 in development. */
export function buildCertificateHandler(appUrl: string): string {
  const u = new URL(appUrl);
  const isLocalhost = u.hostname === "localhost" || u.hostname === "127.0.0.1";
  if (!isLocalhost) return "";
  return `
  // Accept self-signed localhost certs (auto-generated by aio --expose)
  app.on('certificate-error', (event, _wc, _url, _err, _cert, cb) => {
    const u = new URL(${JSON.stringify(appUrl)});
    if (u.hostname === 'localhost' || u.hostname === '127.0.0.1') { event.preventDefault(); cb(true); }
    else cb(false);
  });`.trim();
}

/** Builds keyboard shortcut handler for reload/DevTools.
 *  F5/Ctrl+R: hard reload. F12/Ctrl+Shift+I: DevTools. */
export function buildKeyboardShortcuts(): string {
  return `
  // Local keyboard shortcuts (only when window has focus — NOT globalShortcut)
  win.webContents.on('before-input-event', (event, input) => {
    if (input.type !== 'keyDown') return;
    const ctrl = input.control || input.meta;
    // F5 / Ctrl+R / Ctrl+Shift+R — hard reload (bypasses cache)
    if (input.key === 'F5' || (ctrl && input.key.toLowerCase() === 'r')) {
      event.preventDefault();
      win.webContents.reloadIgnoringCache();
    }
    // F12 / Ctrl+Shift+I — toggle DevTools
    if (input.key === 'F12' || (ctrl && input.shift && input.key.toLowerCase() === 'i')) {
      event.preventDefault();
      win.webContents.toggleDevTools();
    }
    // Ctrl+Shift+Delete — clear all caches and hard reload
    if (ctrl && input.shift && input.key === 'Delete') {
      event.preventDefault();
      win.webContents.session.clearCache().then(() => {
        win.webContents.session.clearStorageData().then(() => {
          win.webContents.reloadIgnoringCache();
        });
      });
    }
  });`.trim();
}

/** Window state persistence helpers — loads/saves window bounds to userData */
export const WINDOW_STATE_HELPERS = `
function loadBounds(dw, dh) {
  try {
    const d = JSON.parse(fs.readFileSync(stateFile, 'utf8'));
    if (d.width > 0 && d.height > 0) return d;
  } catch {}
  return { width: dw, height: dh };
}

function saveBounds(win) {
  try { fs.writeFileSync(stateFile, JSON.stringify(win.getBounds())); } catch {}
}
`.trim();
